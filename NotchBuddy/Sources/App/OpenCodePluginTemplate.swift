import Foundation

// MARK: - OpenCode plugin template
//
// Generates the JS plugin Coucou installs at ~/.config/opencode/plugins/coucou.js
// (see HookServer.openCodePluginURL). Pure string building: no AppKit, no I/O,
// so tests compile this file on its own (scripts/test-opencode-plugin.sh).
//
// The template is a dual export: OpenCode 2 requires a default definition with
// an id and a setup function — it refuses the V1-only named export with
// "Plugin must export a default definition…" (#609) — while OpenCode 1 loads
// the named export. V2 event types and the cross-instance claim deduplication
// were verified against OpenCode 2.0.29's public event stream: one plugin
// instance loads per location, every instance sees the global stream, and the
// types actually emitted are session.created / session.execution.started /
// session.execution.succeeded (session.idle and session.deleted never fire).

enum OpenCodePluginTemplate {
    static func build(hookScriptPath: String) -> String {
        let path = hookScriptPath
            .replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "'", with: "\\'")
        return """
// Coucou plugin for OpenCode — generated by Coucou.app
// Forwards every event to the Coucou notch (fire-and-forget, never blocks).
// Dual export: OpenCode 2 requires a default definition with an id and a
// setup function; OpenCode 1 loads the named export at the bottom.

import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const HOOK = '\(path)';

// OpenCode 2 event types, verified against the public event stream of
// OpenCode 2.0.29. The 1.x types (session.idle, session.error,
// session.deleted) never fire on 2.x; they live in V1_EVENTS below.
const V2_EVENTS = {
  'session.created': 'SessionStart',
  'session.execution.started': 'UserPromptSubmit',
  'session.execution.succeeded': 'Stop',
  'session.execution.failed': 'StopFailure',
  'permission.asked': 'PermissionRequest',
};
const V1_EVENTS = {
  'session.created': 'SessionStart',
  'session.idle': 'Stop',
  'session.error': 'StopFailure',
  'session.deleted': 'SessionEnd',
  'permission.asked': 'PermissionRequest',
};

function forward(hook_event_name, payload) {
  const p = spawn('/bin/sh', [HOOK, '--agent', 'opencode'],
                  { stdio: ['pipe', 'ignore', 'ignore'], detached: true });
  p.on('error', () => {});
  p.stdin.on('error', () => {});
  p.stdin.write(JSON.stringify({ hook_event_name, ...payload }) + '\\n');
  p.stdin.end();
  p.unref();
}

// OpenCode 2 loads one plugin instance per location, and every instance sees
// the global event stream, so a session event arrives once per instance.
// Each stream event carries a unique id: instances race an atomic O_EXCL
// create on a claim file named after it, and only the winner forwards. The
// tool hooks are invoked once, by the owning location's runtime, so they
// need no deduplication.
const CLAIMS_DIR = path.join(os.tmpdir(), 'coucou-opencode-claims');
const CLAIM_MAX_AGE_MS = 24 * 60 * 60 * 1000;

function claimEvent(eventID) {
  const file = path.join(CLAIMS_DIR, eventID.replace(/[^A-Za-z0-9_-]/g, '_'));
  try {
    fs.closeSync(fs.openSync(file, 'wx'));
    return true;
  } catch (err) {
    // The temp dir can be purged while the service runs; recreate and retry.
    if (err && err.code === 'ENOENT') {
      try { fs.mkdirSync(CLAIMS_DIR, { recursive: true }); } catch {}
      try { fs.closeSync(fs.openSync(file, 'wx')); return true; } catch {}
    }
    return false;
  }
}

function ensureClaimsDir() {
  try {
    fs.mkdirSync(CLAIMS_DIR, { recursive: true });
    const cutoff = Date.now() - CLAIM_MAX_AGE_MS;
    for (const name of fs.readdirSync(CLAIMS_DIR)) {
      try {
        const file = path.join(CLAIMS_DIR, name);
        if (fs.statSync(file).mtimeMs < cutoff) fs.unlinkSync(file);
      } catch {}
    }
  } catch {}
}

// --- OpenCode 2 ---
export default {
  id: 'coucou',
  async setup(ctx) {
    const directory = ctx.location?.directory ?? '';
    ensureClaimsDir();

    const controller = new AbortController();
    void (async () => {
      try {
        for await (const event of ctx.event.subscribe({ signal: controller.signal })) {
          const hook_event_name = V2_EVENTS[event?.type];
          if (!hook_event_name) continue;
          const sessionID = event?.data?.sessionID;
          if (typeof sessionID !== 'string' || sessionID === '') continue;
          const eventID = typeof event?.id === 'string' ? event.id : '';
          if (eventID === '' || !claimEvent(eventID)) continue;
          forward(hook_event_name, {
            session_id: sessionID,
            cwd: event?.location?.directory ?? directory,
          });
        }
      } catch {}
    })();

    const registrations = [];
    registrations.push(await ctx.tool.hook('execute.before', (event) => {
      forward('PreToolUse', {
        session_id: event?.sessionID ?? '',
        cwd: directory,
        tool_name: typeof event?.tool === 'string' ? event.tool : '',
        tool_input: event?.input ?? null,
      });
    }));
    registrations.push(await ctx.tool.hook('execute.after', (event) => {
      forward('PostToolUse', {
        session_id: event?.sessionID ?? '',
        cwd: directory,
        tool_name: typeof event?.tool === 'string' ? event.tool : '',
      });
    }));

    return () => {
      controller.abort();
      for (const registration of registrations) {
        if (registration && typeof registration.dispose === 'function') {
          void registration.dispose();
        }
      }
    };
  },
};

// --- OpenCode 1 ---
export const CoucouPlugin = async (_ctx) => ({
  event: async ({ event }) => {
    const hook_event_name = V1_EVENTS[event.type];
    if (!hook_event_name) return;
    const props = event.properties || {};
    const payload = {
      session_id: event.sessionID || event.session_id || props.sessionID || props.session_id || '',
      cwd: event.cwd || event.directory || props.cwd || props.directory || '',
    };
    if (typeof props.tool === 'string') payload.tool_name = props.tool;
    if (props.input != null) payload.tool_input = props.input;
    forward(hook_event_name, payload);
  },
  'tool.execute.before': async (input) => {
    forward('PreToolUse', {
      session_id: input.sessionID || input.session_id || '',
      cwd: input.cwd || '',
      tool_name: typeof input.tool === 'string' ? input.tool : '',
      tool_input: input.input ?? null,
    });
  },
  'tool.execute.after': async (input, _output) => {
    forward('PostToolUse', {
      session_id: input.sessionID || input.session_id || '',
      cwd: input.cwd || '',
      tool_name: typeof input.tool === 'string' ? input.tool : '',
    });
  },
});
"""
    }
}
